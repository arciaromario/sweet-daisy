// Concatenates every migration plus the seed into supabase/setup.sql, a single file that can be
// pasted into the Supabase SQL Editor to set up a fresh project in one go.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = 'supabase/migrations';
const parts = readdirSync(dir)
  .filter((f) => f.endsWith('.sql'))
  .sort()
  .map((f) => `-- ===== ${f} =====\n\n${readFileSync(`${dir}/${f}`, 'utf8')}`);
parts.push(`-- ===== seed.sql =====\n\n${readFileSync('supabase/seed.sql', 'utf8')}`);

writeFileSync(
  'supabase/setup.sql',
  `-- Sweet Daisy — full database setup (generated by \`npm run db:setup\`; do not edit by hand).\n-- Paste into Supabase → SQL Editor → Run, on a NEW project.\n\n${parts.join('\n\n')}`,
);
console.log('supabase/setup.sql written');
